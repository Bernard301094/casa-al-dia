const preferenceKey = 'casa-language';
const languages = {
  'es-419': 'Español (Latinoamérica)',
  'pt-BR': 'Português (Brasil)',
};
const savedLocale = localStorage.getItem(preferenceKey);
let currentLocale = Object.hasOwn(languages,savedLocale) ? savedLocale : 'es-419';
document.documentElement.lang = currentLocale;

export function locale() {
  return currentLocale;
}

export function setLocale(next) {
  if (!Object.hasOwn(languages,next)) return;
  currentLocale = next;
  localStorage.setItem(preferenceKey,next);
  document.documentElement.lang = next;
}

export function t(message, values = {}) {
  const text = locale()==='pt-BR' && Object.hasOwn(portuguese,message) ? portuguese[message] : message;
  return text.replace(/\{(\w+)\}/g,(token,key)=>Object.hasOwn(values,key)?values[key]:token);
}

export function plural(count, singular, multiple) {
  const formatted = new Intl.NumberFormat(locale()).format(count);
  return t(count===1?singular:multiple,{count:formatted});
}

export function languageControl() {
  return '<label class="language-control"><span>'+t('Idioma')+'</span><select id="app-language">'+
    Object.entries(languages).map(([code,label])=>'<option lang="'+code+'" value="'+code+'"'+(code===locale()?' selected':'')+'>'+label+'</option>').join('')+
    '</select></label>';
}
